def _sha256(obj: Any) -> str:
    """Deterministic SHA-256 of any JSON-serialisable object."""
    raw = json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(raw.encode()).hexdigest()


