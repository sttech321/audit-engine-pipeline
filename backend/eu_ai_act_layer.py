# CLI — standalone usage for quick testing
# ══════════════════════════════════════════════════════════════════════════════

def _cli():
    """
    Command-line entry point.

    Usage (after running rim_os_v2 and saving JSON):
        python eu_ai_act_layer.py rim_report.json

    Or integrate directly:
        python -c "
        from rim_os_v2 import build_genesis, audit_file
        from eu_ai_act_layer import attach_to_report
        import json
        g = build_genesis()
        r = audit_file('model.safetensors', genesis=g)
        attach_to_report(r)
        print(json.dumps(r['EU_AI_ACT_FULL']['conformity'], indent=2))
        "
    """
    import argparse, json as _json

    parser = argparse.ArgumentParser(
        description="Build EU AI Act compliance layer from a rim_os_v2 JSON report."
    )
    parser.add_argument("report_json", help="Path to rim_os_v2 JSON report file")
    parser.add_argument(
        "--out", default=None,
        help="Output path for EU AI Act JSON (default: stdout)"
    )
    args = parser.parse_args()

    with open(args.report_json, "r", encoding="utf-8") as f:
        rim_report = _json.load(f)

    eu_report = build_eu_ai_act_report(rim_report)

    output = _json.dumps(eu_report, indent=2, ensure_ascii=False)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(output)
        print(f"[eu_ai_act_layer] Written to {args.out}")
        print(f"[eu_ai_act_layer] Compliance status: {eu_report['conformity']['compliance_status']}")
    else:
        print(output)


if __name__ == "__main__":
    _cli()
