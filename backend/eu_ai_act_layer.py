def _art14_oversight_block(rim_report: Dict) -> Dict:
    """
    Art. 14 — Human Oversight.

    Specifies when and how a human must intervene, based on
    live audit metrics from the report.
    """
    summary   = _extract_summary(rim_report)
    req_rev   = summary.get("requires_human_review", True)
    ano_frac  = summary.get("anomaly_fraction", 0.0)
    bias_pen  = summary.get("bias_penalty_0_1", 0.0)
    risk_level = summary.get("risk_level", "UNKNOWN")

    # Build concrete triggers
    triggers_active: List[str] = []
    if req_rev:
        triggers_active.append("requires_human_review flag is SET")
    if ano_frac > _ANOMALY_REVIEW_FRAC:
        triggers_active.append(
            f"anomaly_fraction {ano_frac:.3f} > threshold {_ANOMALY_REVIEW_FRAC}"
        )
    if bias_pen > _BIAS_REVIEW_THRESHOLD:
        triggers_active.append(
            f"bias_penalty {bias_pen:.3f} > threshold {_BIAS_REVIEW_THRESHOLD}"
        )
    if risk_level == "HIGH":
        triggers_active.append("risk_level is HIGH")

    review_status = "REQUIRED" if triggers_active else "NOT REQUIRED"

    return {
        "article":             "Art. 14 — Human Oversight",
        "oversight_mechanism": "Automated flag + mandatory human review queue",
        "review_status":       review_status,
        "triggers_active":     triggers_active if triggers_active else ["None — all thresholds within bounds"],
        "override_conditions": [
            f"Manual review required if anomaly_fraction > {_ANOMALY_REVIEW_FRAC}",
            f"Manual review required if bias_penalty_0_1 > {_BIAS_REVIEW_THRESHOLD}",
            "Manual review required if risk_level == HIGH",
            "Manual review required if requires_human_review == True",
        ],
        "oversight_capabilities": [
            "Auditor can inspect per-chunk manifold hashes to localise anomalies",
            "Full chunk-level audit trail available in parent report",
            "Ledger hash chain allows verification of audit integrity",
            "SVG/PDF report provides visual Penrose manifold for human interpretation",
        ],
        "human_review_recommended": req_rev,
    }


