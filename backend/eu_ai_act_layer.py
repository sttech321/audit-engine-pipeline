def build_eu_ai_act_report(rim_report: Dict) -> Dict[str, Any]:
    """
    Build a full EU AI Act compliance report from a rim_os_v2 audit report.

    Parameters
    ----------
    rim_report : dict
        The dictionary returned by rim_os_v2.audit_file().

    Returns
    -------
    dict
        Structured EU AI Act report. All fields are JSON-serialisable.
        Attach to the parent report as:
            rim_report["EU_AI_ACT_FULL"] = build_eu_ai_act_report(rim_report)

    Example
    -------
    >>> from rim_os_v2 import build_genesis, audit_file
    >>> from eu_ai_act_layer import build_eu_ai_act_report
    >>> genesis = build_genesis()
    >>> report  = audit_file("model.safetensors", genesis=genesis)
    >>> report["EU_AI_ACT_FULL"] = build_eu_ai_act_report(report)
    """
    summary = _extract_summary(rim_report)

    art9  = _art9_risk_block(rim_report)
    art10 = _art10_data_block(rim_report)
    art11 = _art11_docs_block(rim_report)
    art12 = _art12_logging_block(rim_report)
    art13 = _art13_transparency_block(rim_report)
    art14 = _art14_oversight_block(rim_report)
    art15 = _art15_robustness_block(rim_report)
    conf  = _conformity_block(art9, art15, summary)

    report: Dict[str, Any] = {
        "meta":                 _meta_block(rim_report),
        "Art_9_risk":           art9,
        "Art_10_data":          art10,
        "Art_11_docs":          art11,
        "Art_12_logging":       art12,
        "Art_13_transparency":  art13,
        "Art_14_oversight":     art14,
        "Art_15_robustness":    art15,
        "conformity":           conf,
    }

    # Deterministic hash of this EU AI Act report (excludes itself to avoid circularity)
    report["audit_hash"] = _sha256(report)
    return report


def attach_to_report(rim_report: Dict) -> Dict:
    """
    Convenience wrapper: build the EU AI Act layer and attach it in-place.

    Adds two keys to rim_report:
        rim_report["EU_AI_ACT_FULL"]  — full structured report (this layer)
        rim_report["EU_AI_ACT_HASH"]  — SHA-256 of the full EU AI Act report

    Returns the modified rim_report.
    """
    eu_report = build_eu_ai_act_report(rim_report)
    rim_report["EU_AI_ACT_FULL"] = eu_report
    rim_report["EU_AI_ACT_HASH"] = eu_report["audit_hash"]
    return rim_report


